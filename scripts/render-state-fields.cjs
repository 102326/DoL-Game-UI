// Fail closed when the pinned renderer introduces an unreviewed whole-state use.
const fs=require('node:fs'),path=require('node:path'),ts=require('typescript'),crypto=require('node:crypto');
function fields(source){
 const ast=ts.createSourceFile('model.js',source,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS),keys=new Set();
 function visit(n){
  if(ts.isIdentifier(n)&&n.text==='V'){
   const p=n.parent;
   if(ts.isBindingElement(p)&&p.name===n&&p.parent.parent.initializer?.getText(ast)==='context'){}
   else if(ts.isPropertyAccessExpression(p)&&p.expression===n)keys.add(p.name.text);
   else if(ts.isElementAccessExpression(p)&&p.expression===n&&p.argumentExpression.getText(ast)==='arm + "arm"'){
    // Reviewed armPosition callers are literals. Reject new callers or escaping aliases.
    keys.add('leftarm');keys.add('rightarm');
   }else throw Error('Unreviewed V use: '+p.getText(ast));
  }
  if(ts.isIdentifier(n)&&n.text==='armPosition'){
   const p=n.parent;
   if(ts.isPropertyAccessExpression(p)&&p.name===n){}
   else if(ts.isFunctionDeclaration(p)&&p.name===n){}
   else if(ts.isCallExpression(p)&&p.expression===n&&p.arguments.length===1&&ts.isStringLiteral(p.arguments[0])&&['left','right'].includes(p.arguments[0].text)){}
   else throw Error('Unreviewed armPosition use: '+p.getText(ast));
  }
  ts.forEachChild(n,visit);
 }visit(ast);return [...keys].sort();
}
module.exports={fields};
if(require.main===module){
 const base=path.resolve(__dirname,'../src/wardrobe'),source=fs.readFileSync(path.join(base,'vendor/isolated-model.js'),'utf8');
 const result='// Generated by scripts/render-state-fields.cjs; complete top-level branches, not nested pruning.\n// Model SHA256: '+crypto.createHash('sha256').update(source).digest('hex')+'\nexport const RENDER_STATE_FIELDS = '+JSON.stringify(fields(source),null,2)+' as const;\n';
 const target=path.join(base,'render-state-fields.ts');
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==result)throw Error('Renderer state manifest stale; regenerate and review');}
 else fs.writeFileSync(target,result);
}
